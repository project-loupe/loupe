	#[test]
	fn network_enabled_commands_use_a_private_namespace() {
		// `build` reads PATH, so it still needs the environment lock.
		let _guard = PROCESS_ENV_LOCK.blocking_lock();
		let cmd = SandboxBuilder::new("/tmp")
			.with_network(SandboxNetworkConfig::default(), Vec::new())
			.build("/bin/true");
		let args: Vec<String> =
			cmd.as_std().get_args().map(|s| s.to_string_lossy().into_owned()).collect();
		assert!(args.iter().any(|a| a == "sandbox-exec"), "args: {args:?}");
		assert!(args.iter().any(|a| a == "--unshare-user"), "args: {args:?}");
		// Bubblewrap only nests the second user namespace the supervisor
		// enters when setup took privileges it then dropped, and mounting
		// a fresh /dev is what does that here. Drop this and every
		// networked sandbox fails with EINVAL from nsenter.
		let dev = args.iter().position(|a| a == "--dev").unwrap_or_else(|| {
			panic!("network-enabled sandboxes must mount a fresh /dev: {args:?}")
		});
		assert_eq!(args[dev + 1], "/dev", "args: {args:?}");
		assert!(
			args.iter().any(|a| a == "--unshare-net"),
			"network-enabled sandboxes must use a private namespace: {args:?}",
		);
		assert!(
			!args.iter().any(|a| a == "--share-net"),
			"network-enabled sandboxes must not share the worker namespace: {args:?}",
		);
	}

