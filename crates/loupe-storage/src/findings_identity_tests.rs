#[test]
fn atomic_m_dao_identity_collision_propagates_without_losing_the_fresh_row() {
	let (db, repo, job) = fixture();
	db.with_conn(|conn| {
		let first =
			insert_with_identity(conn, repo, job, &sample("first"), false, 1, || Ok([3; 16]))?
				.unwrap();
		assert!(insert_with_identity(conn, repo, job, &sample("distinct"), false, 2, || Ok(
			[3; 16]
		))
		.is_err());
		assert_eq!(identity(conn, first)?, Value::Blob(vec![3; 16]));
		assert_eq!(conn.query_row("SELECT count(*) FROM findings", [], |r| r.get::<_, i64>(0))?, 1);
		let fresh =
			insert_with_identity(conn, repo, job, &sample("distinct"), false, 3, || Ok([4; 16]))?
				.unwrap();
		assert_ne!(first, fresh);
		assert_eq!(identity(conn, fresh)?, Value::Blob(vec![4; 16]));
		assert_eq!(
			insert_with_identity(conn, repo, job, &sample("first"), false, 4, || Ok([5; 16]))?,
			None
		);
		assert_eq!(identity(conn, first)?, Value::Blob(vec![3; 16]));
		Ok(())
	})
	.unwrap();
}

#[test]
fn atomic_m_dao_entropy_failure_leaves_no_partially_created_finding() {
	let (db, repo, job) = fixture();
	db.with_conn(|conn| {
		let result = insert_with_identity(conn, repo, job, &sample("entropy"), false, 1, || {
			Err(rusqlite::Error::InvalidQuery)
		});
		assert!(matches!(result, Err(rusqlite::Error::InvalidQuery)));
		assert_eq!(conn.query_row("SELECT count(*) FROM findings", [], |r| r.get::<_, i64>(0))?, 0);
		assert!(insert_with_identity(conn, repo, job, &sample("entropy"), false, 2, || Ok(
			[6; 16]
		))?
		.is_some());
		Ok(())
	})
	.unwrap();
}

#[test]
fn report_completion_must_not_mark_a_recycled_finding_id() {
	let (db, repo, job) = fixture();
	let selected = db
		.with_conn(|conn| {
			let selected =
				insert_or_ignore(conn, repo, job, &sample("selected"), false, 0)?.unwrap();
			conn.execute("UPDATE findings SET state='confirmed' WHERE id=?1", [selected])?;
			Ok(selected)
		})
		.unwrap();
	let mut prepared = match crate::scope::with_operator_repository(
		&db,
		&crate::test_support::operator_ingress(),
		crate::scope::OperatorTarget::Finding(selected),
		|scope| crate::reports::prepare_operator(scope, selected),
	)
	.unwrap()
	{
		crate::reports::Preparation::Ready(prepared) => prepared,
		_ => panic!("selected confirmed finding must prepare"),
	};
	db.with_conn(|conn| {
		let original_identity = identity(conn, selected)?;
		conn.execute("DELETE FROM findings WHERE id=?1", [selected])?;
		let replacement =
			insert_or_ignore(conn, repo, job, &sample("selected"), false, 0)?.unwrap();
		assert_eq!(selected, replacement, "exercise real SQLite row-id reuse");
		assert_ne!(original_identity, identity(conn, replacement)?);
		conn.execute("UPDATE findings SET state='confirmed' WHERE id=?1", [replacement])?;
		Ok(())
	})
	.unwrap();
	assert!(
		matches!(prepared.mark_one(&db, selected, 1), Err(crate::Error::ReportReceipt)),
		"completion must reject a replacement row selected only by stale ID"
	);
	assert_eq!(
		db.with_conn(|conn| Ok(get_raw(conn, selected)?.unwrap().state)).unwrap(),
		FindingState::Confirmed
	);
}
