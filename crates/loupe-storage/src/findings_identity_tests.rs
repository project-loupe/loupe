//! Finding identity generation, collision handling and read validation.
use rusqlite::types::Value;

use super::tests::{fixture, sample};
use super::*;

fn identity(conn: &Connection, id: i64) -> rusqlite::Result<Value> {
	conn.query_row("SELECT report_identity FROM findings WHERE id=?1", [id], |r| r.get(0))
}

fn historical(conn: &Connection, repo: i64, job: i64, fingerprint: &str) -> rusqlite::Result<i64> {
	conn.execute("INSERT INTO findings(repo_id,job_id,scanner_id,severity,title,description,fingerprint,state,verification_required,created_at,report_identity) VALUES(?1,?2,'regex','high','historical title','description',?3,'pending',0,0,?4)", params![repo,job,fingerprint,[9u8;16].as_slice()])?;
	Ok(conn.last_insert_rowid())
}

#[test]
fn atomic_m_dao_new_finding_has_a_report_identity() {
	let (db, repo, job) = fixture();
	db.with_conn(|conn| {
		let id = insert_or_ignore(conn, repo, job, &sample("new-identity"), false, 1)?.unwrap();
		assert!(
			matches!(identity(conn,id)?, Value::Blob(bytes) if bytes.len()==16),
			"new finding must own a 16-byte report identity"
		);
		Ok(())
	})
	.unwrap();
}

#[test]
fn atomic_m_dao_duplicate_keeps_the_existing_identity_control() {
	let (db, repo, job) = fixture();
	db.with_conn(|conn| {
		let id = historical(conn, repo, job, "duplicate-identity")?;
		assert_eq!(
			insert_or_ignore(conn, repo, job, &sample("duplicate-identity"), false, 2)?,
			None
		);
		assert_eq!(identity(conn, id)?, Value::Blob(vec![9; 16]));
		assert_eq!(conn.query_row("SELECT count(*) FROM findings", [], |r| r.get::<_, i64>(0))?, 1);
		Ok(())
	})
	.unwrap();
}

#[test]
fn atomic_m_dao_recycled_rowid_has_a_fresh_identity() {
	let (db, repo, job) = fixture();
	db.with_conn(|conn| {
		let old_id = historical(conn, repo, job, "deleted-identity")?;
		let old_identity = identity(conn, old_id)?;
		conn.execute("DELETE FROM findings WHERE id=?1", [old_id])?;
		let new_id =
			insert_or_ignore(conn, repo, job, &sample("replacement-identity"), false, 2)?.unwrap();
		assert_eq!(old_id, new_id, "exercise actual SQLite rowid reuse");
		let new_identity = identity(conn, new_id)?;
		assert!(
			matches!(&new_identity,Value::Blob(bytes) if bytes.len()==16),
			"replacement finding must own a fresh report identity"
		);
		assert_ne!(
			new_identity, old_identity,
			"a stale report receipt must not identify the replacement"
		);
		Ok(())
	})
	.unwrap();
}

#[test]
fn atomic_m_dao_only_fingerprint_conflicts_are_ignored() {
	let (db, repo, job) = fixture();
	db.with_conn(|conn| {
		insert_or_ignore(conn, repo, job, &sample("first-identity"), false, 1)?.unwrap();
		// A deterministic independent UNIQUE constraint exercises the conflict
		// policy without replacing OS randomness or guessing generated bytes.
		conn.execute("CREATE UNIQUE INDEX fixture_unique_title ON findings(title)", [])?;
		assert!(
			insert_or_ignore(conn, repo, job, &sample("distinct-fingerprint"), false, 2).is_err(),
			"non-fingerprint uniqueness failures must propagate"
		);
		assert_eq!(conn.query_row("SELECT count(*) FROM findings", [], |r| r.get::<_, i64>(0))?, 1);
		Ok(())
	})
	.unwrap();
}

